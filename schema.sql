create table if not exists public.loans (
  id bigint generated by default as identity primary key,
  member_name text not null check (length(trim(member_name)) > 0),
  book_title text not null check (length(trim(book_title)) > 0),
  loan_date date not null,
  due_date date not null,
  return_date date,
  status text not null default 'Dipinjam' check (status in ('Dipinjam', 'Dikembalikan', 'Terlambat')),
  created_at timestamptz not null default now(),
  constraint valid_due_date check (due_date >= loan_date),
  constraint valid_return_date check (return_date is null or return_date >= loan_date),
  constraint valid_return_status check ((status = 'Dikembalikan' and return_date is not null) or (status <> 'Dikembalikan' and return_date is null))
);
create index if not exists loans_status_idx on public.loans(status);
